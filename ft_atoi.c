#include "philo.h"

int	ft_atoi(char *str , int *c)
{
	int		i;
	long	r;
	int		s;

	i = 0;
	r = 0;
	s = 1;
	while ((str[i] == 32) || (str[i] >= 9 && str[i] <= 13))
		i++;
	if ((str[i] == 43) || (str[i] == 45))
	{
		if (str[i] == 45)
			s *= -1;
		i++;
	}
	while (str[i] >= 48 && str[i] <= 57)
	{
		r = r * 10 + (str[i] - 48);
		if((r * s) > INT_MAX || (r * s) < INT_MIN)
			*c = -1;
		i++;
	}
	return (r * s);
}
